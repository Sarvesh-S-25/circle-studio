import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import fs from 'node:fs';
import { startServer } from '../helpers/server.mjs';
import { makeMiniProject, rmDir } from '../helpers/project.mjs';
import { createCodexAdapter } from '../../backend/lib/engines/codex.mjs';

test('Codex-only product: structured advisor, limits, history, saved chats, tasks, diagnostics and restore', async () => {
  const s = await startServer({ adapters: () => [createCodexAdapter({ bin: process.execPath, prefixArgs: [path.resolve('tests/helpers/fake-engines.mjs'), 'codex'] })] });
  const root = makeMiniProject();
  try {
    const id = (await s.call('POST', '/api/projects', { path: root, permissions: { claude: true, write: true, run: true } })).json.project.id;
    await s.call('PUT', '/api/settings', { preferredEngine: 'codex' });
    const mcp = await s.call('POST', '/api/changes/preview', { projectId: id, ops: [{ op: 'codex-mcp-set', server: 'dummy', config: { command: 'dummy-server.exe', args: [] } }] });
    assert.equal(mcp.status, 200, JSON.stringify(mcp.json));
    assert.equal((await s.call('POST', '/api/changes/apply', { id: mcp.json.preview?.id || mcp.json.id })).status, 200);
    const configFile = path.join(root, '.codex', 'config.toml');
    const beforeConfig = fs.readFileSync(configFile, 'utf8');
    const verifyConnection = s.app.changes.verifyConnection;
    s.app.changes.verifyConnection = async () => false;
    const repair = await s.call('POST', '/api/changes/preview', { projectId: id, ops: [{ op: 'codex-mcp-set', server: 'dummy', config: { command: 'broken-fixture.exe' }, verify: true }] });
    const rolledBack = await s.call('POST', '/api/changes/apply', { id: repair.json.id });
    assert.equal(rolledBack.json.rolledBack, true, JSON.stringify(rolledBack.json));
    assert.equal(fs.readFileSync(configFile, 'utf8'), beforeConfig, 'failed retest restores exact unrelated TOML and previous settings');
    s.app.changes.verifyConnection = verifyConnection;
    const advice = await s.call('POST', '/api/advisor', { engine: 'codex', source: { type: 'text', text: 'Review this dummy plan.', name: 'plan.md' } });
    assert.equal(advice.status, 200, JSON.stringify(advice.json));
    assert.match(advice.json.summary, /Dummy/);
    const history = (await s.call('GET', `/api/projects/${id}/history?engine=codex`)).json;
    assert.equal(history.conversations[0].engine, 'codex');
    const key = s.app.sessions.chatKey(id, null, 'codex');
    const original = await s.app.chats.append(key, [{ role: 'user', engine: 'codex', text: 'Original fixture' }], 'fake-codex-history-1');
    const copy = await s.call('POST', `/api/projects/${id}/chat/link`, { engine: 'codex', source: 'circle', sessionId: original.conversationId, fork: true });
    assert.equal(copy.status, 200);
    assert.notEqual(copy.json.conversationId, original.conversationId);
    assert.equal(s.app.chats.get(key).fork, true);
    assert.equal(s.app.chats.get(key).sessionId, 'fake-codex-history-1');
    assert.equal(s.app.chats.read(key, original.conversationId).messages[0].text, 'Original fixture');
    const handoff = await s.call('POST', `/api/projects/${id}/progress`, { action: 'record-handoff', sourceEngine: 'codex', targetEngine: 'codex', conversationId: original.conversationId, summary: 'Reviewed dummy decisions and remaining checks.', reviewed: true });
    assert.equal(handoff.json.handoff.type, 'handoff-prepared');
    assert.equal(handoff.json.handoff.sourceMessages, 1);
    assert.equal(s.app.sessions.runs.size, 0, 'preparing a handoff never starts a model turn');
    const pinned = await s.call('GET', `/api/widgets/chat?projectId=${id}&engine=codex&conversationId=${original.conversationId}`);
    assert.equal(pinned.json.pinned, true);
    assert.equal(pinned.json.messages[0].text, 'Original fixture');
    assert.equal(s.app.chats.get(key).conversationId, copy.json.conversationId, 'reading a pin does not change the selected conversation');
    await s.call('PUT', '/api/settings', { widgets: [{ kind: 'chat', size: 'm', projectId: id, engine: 'codex' }] });
    const pin = await s.call('POST', '/api/widgets/pick', { index: 0, conversationId: original.conversationId });
    assert.equal(pin.json.widget.conversationId, original.conversationId);
    const anotherKey = s.app.sessions.chatKey(id, 'other-node', 'codex');
    const unrelated = await s.app.chats.append(anotherKey, [{ role: 'user', text: 'Unrelated node' }]);
    assert.notEqual((await s.call('POST', '/api/widgets/pick', { index: 0, conversationId: unrelated.conversationId })).status, 200, 'a pin cannot read another workflow node');
    const limits = (await s.call('GET', '/api/limits?engine=codex&fresh=1')).json;
    assert.equal(limits.limits.windows[0].pct, 24);
    assert.equal((await s.call('GET', '/api/limits?engine=claude')).json.limits, null);
    const badTask = await s.call('POST', `/api/projects/${id}/progress`, { title: 'Review me', status: 'done' });
    assert.equal(badTask.status, 400);
    const task = await s.call('POST', `/api/projects/${id}/progress`, { title: 'Checked', status: 'done', engine: 'codex', reviewed: true, evidence: [{ kind: 'manual', detail: 'Reviewed dummy result.' }] });
    assert.equal(task.json.summary.done, 1);
    assert.equal((await s.call('GET', '/api/system/diagnostics')).json.memory.rss > 0, true);
    const backup = (await s.call('POST', '/api/storage/backup', {})).json.backup;
    const prepared = (await s.call('POST', '/api/storage/backup', { download: true })).json;
    assert.equal((await s.call('GET', `/api/storage/download/${prepared.token}`)).json.schema, 'circle-backup/1');
    assert.equal((await s.call('GET', '/api/storage/download/00000000-0000-0000-0000-000000000000')).status, 409);
    const preview = await s.call('POST', '/api/storage/restore', { backup });
    assert.equal(preview.status, 200);
    assert.equal((await s.call('POST', '/api/storage/restore', { id: preview.json.id })).json.verified, true);
  } finally { await s.close(); rmDir(root); }
});
